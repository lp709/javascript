let result;
let number1 = 5;
let number2 = 2;
let symbol = "*";

if (symbol == "/") {
    result = number1 / number2;
    console.log(`Result: ${result}`);
}
else if (symbol == "-") {
    result = number1 - number2;
    console.log(`Result: ${result}`);
}
else if (symbol == "+") {
    result = number1 + number2;
    console.log(`Result: ${result}`);
}
else if (symbol == "*") {
    result = number1 * number2;
    console.log(`Result: ${result}`);
}
